# Default larger set (200 questions) generated by make_eval200.py. If the file
# exists it is used automatically; otherwise the inline 31-case set above runs.
# Override with EVAL_FILE=path/to/cases.jsonl.
DEFAULT_EVAL_FILE = "data/eval/qa_200.jsonl"


def load_cases() -> List[QA]:
    path = Path(os.environ.get("EVAL_FILE", DEFAULT_EVAL_FILE))
    if not path.exists():
        return QA_CASES
    cases: List[QA] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        d = json.loads(line)
        cases.append(QA(d["q"], d["facts"], d.get("scope", "in")))
    return cases or QA_CASES


def score_answer(qa: QA, answer: str) -> dict:
    a = answer.replace(" ", "")
    ko = LATIN_RUN.search(answer) is None
    concise = len(answer) <= LEN_LIMIT
    if qa.scope == "in":
        fact = any(f.replace(" ", "") in a for f in qa.facts)
        declined = False
        ok = fact and ko and concise
    else:                                  # out-of-scope: correct = a clean refusal
        declined = any(f.replace(" ", "") in a for f in qa.facts)
        fact = declined
        ok = declined and ko and concise
    return {"ok": ok, "fact": fact, "ko": ko, "concise": concise,
            "declined": declined, "len": len(answer)}


def run_qa_eval(bot: WelfareAssistant, cases: List[QA] = None,
                verbose: bool = False) -> dict:
    """Run the labelled QA set through `bot` and return aggregate metrics.

    Reusable by eval_models.py: swap bot.llm between calls to compare models
    on the same RAG index. `cases` defaults to load_cases() (200-question file
    if present, else the inline set).
    """
    if cases is None:
        cases = load_cases()
    n = len(cases)
    agg = {"ok": 0, "fact": 0, "ko": 0, "concise": 0}
    scope = {"in": [0, 0], "out": [0, 0]}      # {scope: [passed, total]}
    total_len = 0.0
    total_lat = 0.0
    failures: List[tuple] = []
    for qa in cases:
        # Fresh history each question so the signal layer can't perturb answers.
        bot.reset_conversation()
        t0 = time.time()
        ans = bot.ask_text(qa.q).answer.strip()
        total_lat += time.time() - t0
        s = score_answer(qa, ans)
        for k in agg:
            agg[k] += int(s[k])
        scope[qa.scope][1] += 1
        scope[qa.scope][0] += int(s["ok"])
        total_len += s["len"]
        if not s["ok"]:
            why = "".join(x for x, ok in
                          (("fact", s["fact"]), ("ko", s["ko"]), ("len", s["concise"]))
                          if not ok) or "?"
            failures.append((qa.scope, qa.q, why, ans))
        if verbose:
            mark = "✓" if s["ok"] else "✗"
            tag = "OUT" if qa.scope == "out" else "in "
            print(f"[{mark}][{tag}] {qa.q}")
    return {"n": n, **agg, "avg_len": total_len / n, "avg_latency": total_lat / n,
            "scope": scope, "failures": failures}


def main():
    print("Loading pipeline (indexing welfare docs + LLM)...\n")
    bot = WelfareAssistant()
    cases = load_cases()
    print(f"RAG backend : {bot.rag.backend} / {bot.rag.embedder.backend}")
    llm_desc = f"{bot.llm.model}" if bot.llm.available else "offline fallback (echo)"
    print(f"LLM backend : {llm_desc}")
    print(f"평가 문항   : {len(cases)}개 "
          f"(정보질문 {sum(c.scope=='in' for c in cases)} / "
          f"범위밖 {sum(c.scope=='out' for c in cases)})\n")

    r = run_qa_eval(bot, cases, verbose=False)
    n = r["n"]

    # Show the failures so weaknesses are visible without printing all answers.
    print("=" * 70)
    print(f" 틀린 문항 ({len(r['failures'])}개)  [실패항목]")
    print("=" * 70)
    for sc, q, why, ans in r["failures"]:
        tag = "OUT" if sc == "out" else "in "
        print(f"[✗{why}][{tag}] {q}")
        print(f"      → {ans[:150]}{'…' if len(ans) > 150 else ''}")
    print("\n" + "=" * 70)
    print(" SUMMARY")
    print("=" * 70)
    print(f"  전체 정답률(pass)   : {r['ok']}/{n} = {r['ok']/n:.0%}")
    ip, it = r["scope"]["in"]
    op, ot = r["scope"]["out"]
    if it:
        print(f"   - 정보 질문(정답)  : {ip}/{it} = {ip/it:.0%}")
    if ot:
        print(f"   - 범위밖(거절)     : {op}/{ot} = {op/ot:.0%}")
    print(f"  정확성(fact hit)    : {r['fact']}/{n} = {r['fact']/n:.0%}")
    print(f"  한국어 준수(no eng) : {r['ko']}/{n} = {r['ko']/n:.0%}")
    print(f"  간결성(<= {LEN_LIMIT}자)  : {r['concise']}/{n} = {r['concise']/n:.0%}")
    print(f"  평균 답변 길이      : {r['avg_len']:.0f}자")
    print(f"  평균 응답 시간      : {r['avg_latency']:.2f}초")
    if not bot.llm.available:
        print("\n  주의: 지금은 오프라인 폴백(검색결과 요약)입니다. Ollama가 켜진 Mac에서\n"
              "  실행하면 실제 모델 답변 품질이 측정됩니다.")


if __name__ == "__main__":
    main()
