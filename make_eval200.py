def main():
    out = Path("data/eval/qa_200.jsonl")
    out.parent.mkdir(parents=True, exist_ok=True)
    rows = []
    for facts, qs in TOPICS.values():
        for q in qs:
            rows.append({"q": q, "facts": facts, "scope": "in"})
    for q in OUT_OF_SCOPE:
        rows.append({"q": q, "facts": OOS_FACTS, "scope": "out"})
    with out.open("w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    n_in = sum(1 for r in rows if r["scope"] == "in")
    n_out = len(rows) - n_in
    print(f"wrote {out}  total={len(rows)}  in-scope={n_in}  out-of-scope={n_out}")


if __name__ == "__main__":
    main()
